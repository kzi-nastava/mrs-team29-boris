package com.example.mobilnaaplikacijatim29.data.model;

public class ReportSummary {
    private int totalRides;
    private double totalKilometers;
    private double totalMoney;
    private double avgRidesPerDay;
    private double avgKilometersPerDay;
    private double avgMoneyPerDay;

    public int getTotalRides() { return totalRides; }
    public double getTotalKilometers() { return totalKilometers; }
    public double getTotalMoney() { return totalMoney; }
    public double getAvgRidesPerDay() { return avgRidesPerDay; }
    public double getAvgKilometersPerDay() { return avgKilometersPerDay; }
    public double getAvgMoneyPerDay() { return avgMoneyPerDay; }
}
